from dataclasses import replace
from typing import Awaitable, Callable
from weakref import WeakKeyDictionary

from core.config import Settings
from core.business_usage import UsageError
from core.llm_utils import RuntimeFailure
from core.usage_observation import DispatchObservation, observe_dispatches
from core.usage_runtime import MeteredAsyncClient
from echomind_core.embedding import DIMENSIONS, EMBEDDING_MODEL
from echomind_core.execution import ExecutionGate
from echomind_core.full_resources import FullResourceConfig, FullRuntimeServices
from echomind_core.integration import AdmittedTravelTurn, IntegratedOutcome, _detach
from echomind_core.provider import MODEL
from echomind_core.storage import StorageConfig, _drain_thread
