RUNTIME = "echomind_travel_full_v2"
_SERVICES: WeakKeyDictionary = WeakKeyDictionary()


def resource_config(settings: Settings) -> FullResourceConfig:
    paths = (settings.assistant_full_template_root, settings.assistant_full_redis_socket,
             settings.assistant_full_chroma_path)
    if any(path is None for path in paths):
        raise RuntimeFailure("full_resources_configuration")
    return FullResourceConfig(storage=StorageConfig(
        namespace=settings.assistant_full_namespace, redis_socket=paths[1], chroma_path=paths[2],
        embedding_model=EMBEDDING_MODEL, embedding_dimensions=DIMENSIONS), template_root=paths[0],
        reviewed_city_id=settings.assistant_full_reference_city,
        reviewed_venue_id=settings.assistant_full_reference_venue,
        vector_receipt_root=settings.assistant_full_vector_receipt_root)


def get_full_services(settings: Settings) -> FullRuntimeServices:
    """One technical Monitor per loop/config; never cache request/owner ports."""
    config, loop = resource_config(settings), asyncio.get_running_loop()
    existing = _SERVICES.get(loop)
    if existing is not None:
        if existing[0] != config:
            raise RuntimeFailure("full_resources_configuration_changed")
        return existing[1]
    service = FullRuntimeServices(config)
    _SERVICES[loop] = (config, service)
    return service


async def close_full_services() -> None:
    item = _SERVICES.pop(asyncio.get_running_loop(), None)
    if item is not None:
        await item[1].aclose()


class AdmittedFullTravelTurn(AdmittedTravelTurn):
    """Same MySQL admission/CAS and authority checks, explicit larger protocol."""
    async def preflight(self, settings: Settings) -> None:
        if self.selection_context is None or settings.assistant_runtime != RUNTIME:
            raise RuntimeFailure("full_resources_context_required")
        if settings.qwen_model != MODEL:
            raise RuntimeFailure("full_resources_model_configuration")
        try:
            configured_endpoint(settings)
        except QwenError:
            raise RuntimeFailure("full_resources_model_configuration") from None
        service = get_full_services(settings)
        prepared = await _drain_thread(service.preflight, self.scope.owner_id)
        # A request never starts Redis/Chroma, DDL or paid index preparation.
        self._service, self._preparation = service, prepared
        self._config = resource_config(settings)
        self._tier = TravelBudgetTier(settings.assistant_full_budget)
        self._display_messages: list[str] = []

    def model_events(self, turn: TravelTurn) -> list[dict]:
        # Reservations must not be synthesized into completed model events.
        return []

    def format_message(self, messages: list[str]) -> str:
        joined = "\n\n".join(messages)
        if len(joined) <= 3000:
            return joined
        if (len(messages) > 4 or any(len(item) > 32_000 for item in messages)
                or sum(len(item.encode()) for item in messages) > 96_000):
            raise RuntimeFailure("reply_limit")
        self._display_messages = list(messages)
        return "已准备本次完整程序资料，正文与来源见接下来的资料投影。相关资料不等于问题已获回答，也不保证今天适用；知识库AI问答仍未开放。"

    async def run(self, settings: Settings, client: MeteredAsyncClient,
                  current: Callable[[], Awaitable[dict]], read_places: Callable[[], Awaitable[dict]],
                  read_preferences: Callable[[], Awaitable[list[dict]]]) -> IntegratedOutcome:
        if (self._used or type(client) is not MeteredAsyncClient or not hasattr(self, "_service")
                or settings.assistant_runtime != RUNTIME or resource_config(settings) != self._config
                or TravelBudgetTier(settings.assistant_full_budget) != self._tier):
            raise RuntimeFailure("runtime_configuration")
        self._used = True
        authority = self.authority(current, read_places, read_preferences)
        bridge = TravelToolBridge(self.snapshot, authority, parallel_reads=True)
        budget = TravelTaskBudget(self._tier)
        active = True

        def current_scope():
            return self.scope if active else None

        gate = ExecutionGate(self.scope, current_scope, budget)
        observed = DispatchObservation(before_dispatch=authority)
        result = None
        ports = None

        def receipt() -> dict:
            models, tools, tokens = budget.counts
            return {"schema_version": "travel-execution-receipt-v1", "budget": budget.summary(),
                    "reservations": {"models": models, "tools": tools, "output_tokens": tokens},
                    "dispatch": observed.summary(), "trace_complete": False}

        def failure_trace(code: str) -> dict:
            return {"runtime_version": VERSION, "role": result.role if result else None,
                    "model_calls": budget.counts[0], "tool_calls": budget.counts[1],
                    "output_tokens_reserved": budget.counts[2], "usage_has_unknown": True,
                    "stop_reason": code, "events": [], "execution_receipt": receipt()}

        try:
            with observe_dispatches(observed):
                await authority()
                package = TravelDomainPackage().capture()
                # Opening/closing local resources is covered by the task clock;
                # cancellation drains native workers before releasing capacity.
                async with asyncio.timeout(budget.remaining_seconds):
                    async with self._service.open_for_turn(self.scope, current_scope, self.preferences,
                            read_preferences, package) as ports:
                        if ports.preflight != self._preparation:
                            raise RuntimeFailure("full_resources_preparation_changed")
                        retrieval = None
                        if ports.vector is not None:
                            retrieval = ReviewedRetrieval(bridge, ports.national,
                                self._config.reviewed_city_id, self._config.reviewed_venue_id,
                                package=package, vector=ports.vector)
                        candidate = FullTravelCandidate(bridge, TravelIntentRecognizer(ports.resources.embedding),
                            package=package, prepared=ports.prepared, memory=ports.memory,
                            national=ports.national, retrieval=retrieval, observation=ports.observation,
                            selection_context=self.selection_context)
                        request = Request(message=self.text, user_id=self.scope.owner_id,
                            conv_id=self.scope.conversation_id, request_id=self.operation,
                            history=[{"role": row["role"], "content": row["text"]}
                                     for row in self.initial["messages"][-6:]])
                        result = await candidate.run(request, gate, settings, client)
                if gate._usage_error is not None:
                    raise gate._usage_error
                await authority()
                outcome = self._project(result)
                exact = receipt()
                trace = outcome.trace | {"runtime_version": VERSION, "execution_receipt": exact}
                metadata = outcome.metadata | {"runtime": RUNTIME, "engine_version": VERSION,
                    "execution_receipt": exact, "program_messages": self._display_messages,
                    "prepared_resources": self._preparation.summary(),
                    "domain_details": _detach(result.versions), "dispatch_semantics": "transport_attempt_not_upstream_acceptance"}
                return replace(outcome, trace=trace, metadata=metadata)
        except BaseException as error:
            code = getattr(error, "code", "cancelled" if isinstance(error, asyncio.CancelledError) else "full_execution_failed")
            trace = failure_trace(code)
            if isinstance(error, TimeoutError):
                wrapped = RuntimeFailure("task_deadline")
                wrapped.trace = failure_trace("task_deadline")
                raise wrapped from None
            if isinstance(error, (RuntimeFailure, UsageError)) or hasattr(error, "trace"):
                error.trace = trace
                raise
            if isinstance(error, asyncio.CancelledError):
                error.trace = trace
                raise
            wrapped = RuntimeFailure("full_execution_failed")
            wrapped.trace = trace
            raise wrapped from None
        finally:
            active = False
            gate.invalidate()
